import { useEffect, useMemo, useState } from 'react'
import { useDispatch, useSelector } from 'react-redux'
import {
  Alert,
  Box,
  Button,
  CircularProgress,
  Dialog,
  DialogActions,
  DialogContent,
  DialogTitle,
  Divider,
  FormControl,
  InputAdornment,
  InputLabel,
  MenuItem,
  Select,
  Stack,
  TextField,
  Typography,
} from '@mui/material'
import { Search } from 'lucide-react'
import ResourceCard from '../../components/cards/ResourceCard'
import {
  fetchStudyMaterials,
  markDownloaded,
  toggleBookmark,
} from '../../store/slices/studyMaterialSlice'

const uniqueValues = (items, key) => [...new Set(items.map((item) => item[key]))]

export default function StudyMaterialsPage() {
  const dispatch = useDispatch()
  const { items, loading, error, bookmarkIds, downloadedIds } = useSelector((state) => state.studyMaterials)
  const [query, setQuery] = useState('')
  const [examination, setExamination] = useState('All')
  const [subject, setSubject] = useState('All')
  const [topic, setTopic] = useState('All')
  const [category, setCategory] = useState('All')
  const [sort, setSort] = useState('newest')
  const [preview, setPreview] = useState(null)
  const [downloadMessage, setDownloadMessage] = useState('')

  useEffect(() => {
    dispatch(fetchStudyMaterials())
  }, [dispatch])

  const results = useMemo(() => {
    const filtered = items.filter((resource) => {
      const searchText = `${resource.title} ${resource.description}`.toLowerCase()
      return searchText.includes(query.toLowerCase())
        && (examination === 'All' || resource.examination === examination)
        && (subject === 'All' || resource.subject === subject)
        && (topic === 'All' || resource.topic === topic)
        && (category === 'All' || resource.category === category)
    })

    return [...filtered].sort((a, b) => {
      if (sort === 'popular') return b.popularity - a.popularity
      if (sort === 'title') return a.title.localeCompare(b.title)
      return new Date(b.createdAt) - new Date(a.createdAt)
    })
  }, [items, query, examination, subject, topic, category, sort])

  const downloadResource = (resource) => {
    const content = [
      resource.title,
      '',
      `Examination: ${resource.examination}`,
      `Subject: ${resource.subject}`,
      `Topic: ${resource.topic}`,
      '',
      resource.description,
      '',
      'This downloadable study summary is generated by ExamPro.',
    ].join('\n')
    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const link = document.createElement('a')
    link.href = url
    link.download = `${resource.title.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}-summary.txt`
    document.body.appendChild(link)
    link.click()
    link.remove()
    URL.revokeObjectURL(url)
    dispatch(markDownloaded(resource.id))
    setDownloadMessage(`${resource.title} downloaded successfully.`)
  }

  const clearFilters = () => {
    setQuery('')
    setExamination('All')
    setSubject('All')
    setTopic('All')
    setCategory('All')
  }

  return (
    <Box sx={{ p: { xs: 2, md: 3 }, maxWidth: 1440, mx: 'auto' }}>
      <Typography variant="h4" sx={{ mb: 0.5 }}>Study Materials</Typography>
      <Typography color="text.secondary" sx={{ mb: 3 }}>Search, preview and download preparation resources.</Typography>
      {downloadMessage && <Alert severity="success" onClose={() => setDownloadMessage('')} sx={{ mb: 2 }}>{downloadMessage}</Alert>}
      {error && <Alert severity="error" sx={{ mb: 2 }}>{error}</Alert>}

      <Box sx={{ p: 2, mb: 3, bgcolor: 'white', border: '1px solid #e9edf4', borderRadius: 2.5 }}>
        <Stack direction={{ xs: 'column', md: 'row' }} spacing={1.5}>
          <TextField
            size="small"
            value={query}
            onChange={(event) => setQuery(event.target.value)}
            placeholder="Search resources"
            sx={{ flex: 1 }}
            slotProps={{ input: { startAdornment: <InputAdornment position="start"><Search size={18} /></InputAdornment> } }}
          />
          <FormControl size="small" sx={{ minWidth: { md: 170 } }}>
            <InputLabel>Examination</InputLabel>
            <Select label="Examination" value={examination} onChange={(event) => setExamination(event.target.value)}>
              <MenuItem value="All">All examinations</MenuItem>
              {uniqueValues(items, 'examination').map((value) => <MenuItem key={value} value={value}>{value}</MenuItem>)}
            </Select>
          </FormControl>
          <FormControl size="small" sx={{ minWidth: { md: 150 } }}>
            <InputLabel>Subject</InputLabel>
            <Select label="Subject" value={subject} onChange={(event) => setSubject(event.target.value)}>
              <MenuItem value="All">All subjects</MenuItem>
              {uniqueValues(items, 'subject').map((value) => <MenuItem key={value} value={value}>{value}</MenuItem>)}
            </Select>
          </FormControl>
          <FormControl size="small" sx={{ minWidth: { md: 150 } }}>
            <InputLabel>Topic</InputLabel>
            <Select label="Topic" value={topic} onChange={(event) => setTopic(event.target.value)}>
              <MenuItem value="All">All topics</MenuItem>
              {uniqueValues(items, 'topic').map((value) => <MenuItem key={value} value={value}>{value}</MenuItem>)}
            </Select>
          </FormControl>
          <FormControl size="small" sx={{ minWidth: { md: 170 } }}>
            <InputLabel>Category</InputLabel>
            <Select label="Category" value={category} onChange={(event) => setCategory(event.target.value)}>
              <MenuItem value="All">All categories</MenuItem>
              {uniqueValues(items, 'category').map((value) => <MenuItem key={value} value={value}>{value}</MenuItem>)}
            </Select>
          </FormControl>
          <FormControl size="small" sx={{ minWidth: { md: 140 } }}>
            <InputLabel>Sort</InputLabel>
            <Select label="Sort" value={sort} onChange={(event) => setSort(event.target.value)}>
              <MenuItem value="newest">Newest</MenuItem>
              <MenuItem value="popular">Most popular</MenuItem>
              <MenuItem value="title">Title A-Z</MenuItem>
            </Select>
          </FormControl>
        </Stack>
      </Box>

      <Stack direction="row" justifyContent="space-between" alignItems="center" sx={{ mb: 2 }}>
        <Typography variant="body2" color="text.secondary">{results.length} resources found</Typography>
        {(query || examination !== 'All' || subject !== 'All' || topic !== 'All' || category !== 'All') && (
          <Button size="small" onClick={clearFilters}>Clear filters</Button>
        )}
      </Stack>
      {loading ? (
        <Box sx={{ py: 8, textAlign: 'center' }}><CircularProgress /></Box>
      ) : (
        <Box sx={{ display: 'grid', gridTemplateColumns: { xs: '1fr', sm: 'repeat(2, 1fr)', lg: 'repeat(3, 1fr)' }, gap: 2 }}>
          {results.map((resource) => (
            <ResourceCard
              key={resource.id}
              resource={resource}
              bookmarked={bookmarkIds.includes(resource.id)}
              downloaded={downloadedIds.includes(resource.id)}
              onBookmark={(id) => dispatch(toggleBookmark(id))}
              onPreview={setPreview}
              onDownload={downloadResource}
            />
          ))}
        </Box>
      )}
      {!loading && !results.length && (
        <Box sx={{ py: 8, textAlign: 'center', bgcolor: 'white', borderRadius: 2.5, border: '1px solid #e9edf4' }}>
          <Typography fontWeight={800}>No resources found</Typography>
          <Typography variant="body2" color="text.secondary" sx={{ mt: 0.5 }}>Try clearing or changing the filters.</Typography>
        </Box>
      )}

      <Dialog open={Boolean(preview)} onClose={() => setPreview(null)} maxWidth="sm" fullWidth>
        {preview && (
          <>
            <DialogTitle>{preview.title}</DialogTitle>
            <DialogContent>
              <Typography variant="body2" color="text.secondary" sx={{ mb: 2 }}>{preview.description}</Typography>
              <Divider sx={{ mb: 2 }} />
              <Stack spacing={1}>
                <Typography variant="body2"><strong>Examination:</strong> {preview.examination}</Typography>
                <Typography variant="body2"><strong>Subject:</strong> {preview.subject}</Typography>
                <Typography variant="body2"><strong>Topic:</strong> {preview.topic}</Typography>
                <Typography variant="body2"><strong>Format:</strong> {preview.format} • {preview.pages} pages • {preview.size}</Typography>
              </Stack>
            </DialogContent>
            <DialogActions sx={{ px: 3, pb: 2 }}>
              <Button onClick={() => setPreview(null)}>Close</Button>
              <Button variant="contained" onClick={() => downloadResource(preview)}>Download summary</Button>
            </DialogActions>
          </>
        )}
      </Dialog>
    </Box>
  )
}
